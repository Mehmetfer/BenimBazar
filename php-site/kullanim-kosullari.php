    <h2>1. Amaç ve kapsam</h2>
    <p>Bu koşullar, BenimBazar web uygulamasının kullanımını düzenler. Platform; araç ve ilgili kategorilerde ilan yayınlama, görüntüleme ve açık özellikler çerçevesinde etkileşim imkânı sunar. BenimBazar bir ilan platformudur; alım-satımın tarafı değildir.</p>

    <h2>2. Tanımlar</h2>
    <ul>
      <li><strong>Platform / BenimBazar:</strong> İlan hizmetini sunan site.</li>
      <li><strong>Kullanıcı:</strong> Üye olan kişi.</li>
      <li><strong>İlan sahibi:</strong> İlanı oluşturan hesap.</li>
      <li><strong>İlan:</strong> Platformda yayınlanan veya moderasyonda bekleyen kayıt ve buna bağlı bilgiler / görseller.</li>
      <li><strong>Staff:</strong> Yönetim paneli yetkili rolleri.</li>
    </ul>

    <h2>3. Üyelik</h2>
    <p>Üyelik için geçerli e-posta, kullanıcı adı, şifre ve istenen iletişim / konum bilgileri gerekir. Kayıtta ülke seçimi (Türkiye / KKTC) yapılabilir. Google ile giriş desteklenebilir.</p>

    <h2>4. Kullanıcı hesabı</h2>
    <p>Hesap güvenliği kullanıcıya aittir. Yanlış bilgi, başkasının kimliği veya kötüye kullanım tespitinde hesap kısıtlanabilir.</p>

    <h2>5. İlan verme</h2>
    <p>İlan vermek için giriş gerekir. Aktif ilan sayısı role göre sınırlı olabilir (üye, kurumsal galeri, VIP Kurumsal). VIP Kurumsal hesaplar sınırsız ilan verebilir. Kota dolunca yeni ilan açılamayabilir.</p>

    <h2>6. İlan bilgilerinin doğruluğu</h2>
    <p>Başlık, açıklama, kategori, konum, fiyat, araç teknik alanları ve ekspertiz beyanları ilan sahibinin sorumluluğundadır. Platform, girilen bilgilerin doğruluğunu otomatik olarak garanti etmez.</p>

    <h2>7. Araç ilanları</h2>
    <p>Marka, model, yıl, kilometre, yakıt, vites, dümen (KKTC hesaplarında istenebilir), fiyat ve para birimi gerçeğe uygun seçilmelidir. Listede olmayan modeller elle yazılabilir; yine de gerçeğe uygun olmalıdır.</p>
    <ul>
      <li>Doğru marka / model seçimi</li>
      <li>Doğru model yılı ve kilometre</li>
      <li>Doğru yakıt ve vites</li>
      <li>Aracın gerçek fotoğraflarının kullanılması</li>
      <li>Başkasına ait veya yanıltıcı fotoğraf kullanılmaması</li>
      <li>Araçta olmayan özelliklerin yazılmaması</li>
      <li>Ekspertiz bilgisinin gerçeğe uygun girilmesi</li>
    </ul>

    <h2>8. Fotoğraf ve içerik kuralları</h2>
    <p>Yalnızca ilana konu araca ait fotoğraflar yüklenmelidir. İzin verilen formatlar ve boyut limitleri uygulanır. İlan fotoğraflarına sistem filigranı uygulanabilir. Yanıltıcı, yasadışı veya başkasının hakkını ihlal eden içerik yasaktır.</p>

    <h2>9. Ekspertiz bilgileri</h2>
    <p>Ekspertiz / kaporta alanı, bu koşullara ek olarak <a class="link-gold" href="/ekspertiz-kosullari.php">Araç Ekspertiz Kullanım ve Sorumluluk Koşulları</a>’na tabidir. Bu alan bağımsız resmi bir ekspertiz raporu değildir.</p>

    <h2>10. Fiyat ve ilan bilgilerinin sorumluluğu</h2>
    <p>Fiyat ve para birimi (ör. TL / sterlin) ilan sahibi tarafından girilir. Platform fiyatın piyasa uygunluğunu veya ödeme süreçlerini üstlenmez.</p>

    <h2>11. Yasaklı içerikler / ilanlar</h2>
    <p>Dolandırıcılık, sahte ilan, yanıltıcı ekspertiz, izinsiz kişisel veri yayını, yasadışı içerik ve benzeri kullanımlar yasaktır.</p>

    <h2>12. İlanın onaylanması, düzenlenmesi ve kaldırılması</h2>
    <p>Yeni ilanlar genellikle moderasyon bekler. Yetkili personel onaylayabilir, reddedebilir, düzenleme isteyebilir veya kaldırabilir. İlan sahibi kendi ilanını (iptal / satıldı kuralları çerçevesinde) güncelleyebilir veya satıldı olarak işaretleyebilir. Süre dolumu ve yeniden yayın özellikleri varsa bunlar ayrıca uygulanır.</p>

    <h2>13. Kullanıcılar arası iletişim</h2>
    <p>Site içi mesajlaşma yapılandırma ile kapalı olabilir. Açık olduğunda güvenli iletişim kuralları geçerlidir. WhatsApp veya harici paylaşım bağlantıları kullanıcı inisiyatifindedir; platform görüşmenin sonucundan sorumlu değildir.</p>

    <h2>14. Dolandırıcılık ve yanıltıcı bilgi</h2>
    <p>Şüpheli ilan veya davranış bildirilmelidir. Platform, makul ölçüde inceleme ve kaldırma yetkisini saklı tutar; tüm zararları önleme garantisi vermez.</p>

    <h2>15. Fikri mülkiyet</h2>
    <p>BenimBazar markası, arayüz ve yazılım unsurları platforma aittir. Kullanıcı, yüklediği içerik üzerinde gerekli haklara sahip olduğunu beyan eder ve platforma ilanı göstermek için gerekli lisansı verir.</p>

    <h2>16. Gizlilik ve kişisel veriler</h2>
    <p>Hesap ve iletişim verileri hizmetin sunulması için işlenebilir. Ayrı bir gizlilik bildirimi yayınlandığında bu koşullarla birlikte okunmalıdır.</p>
    <p class="legal-page__note">Türkiye ve KKTC kişisel veri mevzuatı detayları için hukuki inceleme gerekir.</p>

    <h2>17. Güvenlik</h2>
    <p>Makul teknik önlemler alınmaya çalışılır; mutlak güvenlik garanti edilmez. Kullanıcı şifresini paylaşmamalıdır.</p>

    <h2>18. Sorumluluk sınırları</h2>
    <p>Platform, kullanıcılar arası işlemlerin tarafı değildir; aracın durumu, mülkiyet, ödeme ve teslimat konularında aracı değildir. Yasaların emredici hükümleri saklıdır.</p>
    <p class="legal-page__note">Sorumluluk sınırının ülkeye göre geçerliliği hukuki inceleme gerektirir.</p>

